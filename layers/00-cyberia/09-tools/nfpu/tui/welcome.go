func (m WelcomeModel) Init() tea.Cmd {
	return welcomeTickCmd()
}

func (m WelcomeModel) Update(msg tea.Msg) (WelcomeModel, tea.Cmd) {
	switch msg.(type) {
	case welcomeTickMsg:
		m.colorIdx = m.colorIdx + 1
		return m, welcomeTickCmd()
	}
	return m, nil
}

func (m WelcomeModel) View() string {
	b := strings.Builder{}

	lines := strings.Split(m.asciiArt, "\n")
	timeVal := float64(m.colorIdx)

	for y, line := range lines {
		for x, ch := range line {
			// Water rippling sine wave based on x, y, and time
			phase := math.Sin(float64(x)*0.1 + float64(y)*0.2 - timeVal*0.5)

			// Normalize from [-1, 1] to [0, len(wavePalette)-1]
			idx := int((phase + 1) * 0.5 * float64(len(wavePalette)-1))
			if idx < 0 {
				idx = 0
			} else if idx >= len(wavePalette) {
				idx = len(wavePalette) - 1
			}

			b.WriteString(wavePalette[idx].Render(string(ch)))
		}
		b.WriteString("\n")
	}

	b.WriteString("\n")
	b.WriteString(BannerStyle.Render(m.banner))
	b.WriteString("\n")
	b.WriteString(HelpStyle.Render("Press [Enter] to begin..."))

	// Center the entire block
	return lipgloss.Place(
		80, 30,
		lipgloss.Center, lipgloss.Center,
		b.String(),
	)
}
