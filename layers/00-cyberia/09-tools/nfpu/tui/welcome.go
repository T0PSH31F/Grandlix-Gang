var wavePalette []lipgloss.Style

func init() {
	colors := []lipgloss.Color{
		lipgloss.Color("#00FFFF"), // Cyan
		lipgloss.Color("#00BFFF"), // Deep Sky Blue
		lipgloss.Color("#1E90FF"), // Dodger Blue
		lipgloss.Color("#4169E1"), // Royal Blue
		lipgloss.Color("#8A2BE2"), // Blue Violet
		lipgloss.Color("#9370DB"), // Medium Purple
		lipgloss.Color("#FF00FF"), // Fuchsia/Pink
		lipgloss.Color("#FF1493"), // Deep Pink
		lipgloss.Color("#FF69B4"), // Hot Pink
	}
	for _, c := range colors {
		wavePalette = append(wavePalette, lipgloss.NewStyle().Foreground(c))
	}
}

type welcomeTickMsg time.Time

func welcomeTickCmd() tea.Cmd {
	return tea.Tick(time.Millisecond*100, func(t time.Time) tea.Msg {
		return welcomeTickMsg(t)
	})
}

